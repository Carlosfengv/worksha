import assert from "node:assert/strict";
import { createHash, randomUUID } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

// Only the enclosing harness's disposable database, signed fixture and loopback
// upstream are used. Source choices never authorize an actual model call.
export async function catalogSourceCases({api, plugin, provider, input, scoped, state, gets, posts, nativeGets, hold, release, data, report}) {
  report.sourceCases = [];
  const passed = (name) => { report.sourceCases.push(name); console.log("通过：" + name); };
  const pluginRef = { pluginId:plugin.manifest.id, digest:plugin.digest };
  const storeId = input.operation.storeId;
  let current = provider;
  const query = () => ({ storeId, providerId:current.id, expectedRevision:String(current.revision) });
  const source = (kind, fields = {}, expected = 200) => api("/api/provider-catalog-source", {kind, query:query(), ...fields}, expected);
  const choose = (s, catalog, expected = 200) => source("select", { sourceRevision:s.sourceRevision, catalog }, expected);
  const read = (s, expected = 200) => source("read", { sourceRevision:s.sourceRevision }, expected);
  const bind = async () => {
    const target = {kind:"saved", providerId:current.id, expectedRevision:String(current.revision)};
    const status = await scoped(storeId, {...pluginRef, action:{kind:"bind", target, allowPrivateNetwork:true}});
    const binding = status.bindings.find((b) => b.providerId === current.id && b.authorized);
    assert(binding);
    return {...pluginRef, bindingId:binding.bindingId, target};
  };
  const initialGets=gets(), initialPosts=posts(), initialNative=nativeGets();
  let remembered = await source("state");
  assert.equal(remembered.kind, "external");
  assert.deepEqual(remembered.choice, pluginRef);
  assert.equal(remembered.authorized, false);
  assert.equal(remembered.selection, null);
  assert.equal(remembered.errorCode, "catalog_source_authorization");
  assert(!JSON.stringify(remembered).includes(current.credentialRef));
  await read(remembered, 403);
  assert.equal(gets(), initialGets); assert.equal(nativeGets(), initialNative); assert.equal(posts(), initialPosts);
  passed("连接结果记住外部目录，但草稿授权不会延续为已保存权限；公开状态不包含草稿凭据引用");
  const sequence=(await api("/api/provider-operations/protocol")).sequence;
  await api("/api/provider-catalog-source", {kind:"state", query:{...query(), storeId:randomUUID()}}, 409);
  await api("/api/provider-catalog-source", {kind:"state", query:{...query(), expectedRevision:"0"}}, 409);
  await choose(remembered, input.catalog, 403);
  await source("select", {sourceRevision:"stale", catalog:null}, 409);
  assert.equal((await api("/api/provider-operations/protocol")).sequence, sequence);
  assert.equal(gets(), initialGets);
  passed("跨数据库、旧连接版本、草稿权限与过期来源令牌均拒绝，不消费旧操作序号");
  let selection=await bind();
  remembered=await choose(remembered, selection);
  assert.equal(remembered.authorized, true); assert.deepEqual(remembered.selection, selection);
  let before=gets();
  const catalog=await read(remembered);
  assert.deepEqual(catalog.models.map((m)=>m.id), ["model-a","model-b","model-false"]);
  assert.equal(gets(), before+2); assert.equal(nativeGets(), initialNative); assert.equal(posts(), initialPosts);
  assert.deepEqual((await api("/api/snapshot")).providers.find((p)=>p.id===current.id), current);
  passed("单独授权已保存连接后，固定来源实际读取两页插件目录，旧 Provider 和模型调用计数不变");
  await state(plugin,"disable");
  const disabled=await source("state"); assert.equal(disabled.kind,"external"); assert.equal(disabled.authorized,false);
  before=gets(); await read(disabled,403); assert.equal(gets(),before); assert.equal(nativeGets(),initialNative);
  await state(plugin,"enable");
  await read(remembered,403);
  selection=await bind(); remembered=await choose(await source("state"),selection);
  await state(plugin,"revoke-grants");
  const revoked=await source("state"); assert.equal(revoked.authorized,false); assert.deepEqual(revoked.choice,pluginRef);
  await read(revoked,403); assert.equal(gets(),before); assert.equal(nativeGets(),initialNative);
  selection=await bind(); remembered=await choose(revoked,selection);
  passed("停用、重新启用和撤权保留来源记忆，旧权限失效时没有原生目录回退");
  before=gets(); const arrived=hold();
  const pending=read(remembered,409);
  await arrived;
  let native=await choose(remembered,null);
  assert.equal(native.kind,"builtin");
  assert.equal((await pending).code,"catalog_source_changed");
  release();
  assert.equal(gets(),before+1); assert.equal(posts(),initialPosts);
  await read(remembered,409); assert.equal(gets(),before+1);
  const nativeCatalog=await read(native);
  assert.deepEqual(nativeCatalog.models.map((m)=>m.id),["native-only"]);
  assert.equal(nativeGets(),initialNative+1);
  report.explicitNativeGets=(report.explicitNativeGets??0)+1;
  const oldNative=native.sourceRevision;
  remembered=await choose(native,selection);
  native=await choose(remembered,null);
  assert.notEqual(native.sourceRevision,oldNative);
  await source("read",{sourceRevision:oldNative},409);
  remembered=await choose(native,selection);
  passed("读取在途切换来源立即丢弃旧结果；只有明确选择内置才读取原生目录，切走再切回也不会复活旧令牌");
  const originalEndpoint=current.endpoint;
  await api("/api/providers",{...current,name:"Renamed saved source",model:"model-b"},200,"PUT");
  const oldQuery=query();
  current=(await api("/api/snapshot")).providers.find((p)=>p.id===current.id);
  await api("/api/provider-catalog-source",{kind:"state",query:oldQuery},409);
  const edited=await source("state"); assert.equal(edited.kind,"external"); assert.equal(edited.authorized,false); assert.deepEqual(edited.choice,pluginRef);
  await read(edited,403);
  selection=await bind(); remembered=await choose(edited,selection);
  await api("/api/providers",{...current,endpoint:originalEndpoint.replace("/custom/","/changed/")},200,"PUT");
  current=(await api("/api/snapshot")).providers.find((p)=>p.id===current.id);
  const changed=await source("state"); assert.equal(changed.kind,"changed"); assert.equal(changed.authorized,false);
  await read(changed,409);
  await api("/api/providers",{...current,endpoint:originalEndpoint},200,"PUT");
  current=(await api("/api/snapshot")).providers.find((p)=>p.id===current.id);
  selection=await bind(); remembered=await choose(await source("state"),selection);
  passed("名称和模型编辑保留实现但要求当前版本授权；端点变化明确标为范围已变，不读取其他来源");
  const stem=createHash("sha256").update(JSON.stringify([storeId,current.id])).digest("hex");
  const file=path.join(data,"provider-configs/catalog-sources",stem+".json");
  const bytes=fs.readFileSync(file), future=JSON.parse(bytes);
  future.version=2; fs.writeFileSync(file,JSON.stringify(future));
  const unknown=fs.readFileSync(file); before=gets();
  await source("state",{},503); await read(remembered,503); await choose(remembered,null,503);
  assert.deepEqual(fs.readFileSync(file),unknown); assert.equal(gets(),before);
  fs.writeFileSync(file,bytes);
  assert.equal((await source("state")).authorized,true);
  const nativeBeforeLoss=nativeGets(); before=gets();
  fs.unlinkSync(file);
  await source("state",{},503); await read(remembered,503); await choose(remembered,null,503);
  assert(!fs.existsSync(file)); assert.equal(gets(),before); assert.equal(nativeGets(),nativeBeforeLoss);
  fs.writeFileSync(file,bytes,{mode:0o600});
  assert.equal((await source("state")).authorized,true);
  report.sourceFileLossVerified=true;
  passed("未知版本保留原字节，来源文件整体丢失也拒绝读取与重选；恢复受管副本后继续使用，没有目录回退");
  assert.deepEqual(await api("/api/catalog-provider-operations/query",input),await api("/api/provider-operations",input.operation));
  return {
    async afterRestart() {
      const before=gets(), nativeBefore=nativeGets();
      const stale=await source("state");
      assert.equal(stale.kind,"external"); assert.deepEqual(stale.choice,pluginRef); assert.equal(stale.authorized,false);
      await read(stale,403); assert.equal(gets(),before); assert.equal(nativeGets(),nativeBefore); assert.equal(posts(),initialPosts);
      assert.equal((await api("/api/catalog-provider-operations/query",input)).status,"committed");
      await scoped(storeId,{...pluginRef,action:{kind:"unbind",bindingId:selection.bindingId}});
      passed("实际进程重启保留外部来源与原回执，但不继承目录授权、不回退或重复探测");
    },
    async afterRemove() {
      const stale=await source("state"); assert.equal(stale.kind,"external"); assert.equal(stale.authorized,false); assert.deepEqual(stale.choice,pluginRef);
      await read(stale,403);
      passed("解除绑定并卸载插件后仍能核查来源记忆，未把缺失实现当作原生目录");
    }
  };
}
