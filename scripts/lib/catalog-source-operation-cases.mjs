import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
export async function catalogSourceOperationCases({api,plugin,provider,scoped,posts,gets,nativeGets,report,control}) {
  report.unifiedSourceCases=[];
  const passed=(name)=>{ report.unifiedSourceCases.push(name); console.log("通过："+name); };
  const protocol=()=>api("/api/provider-operations/protocol");
  const query=(p,storeId)=>({storeId,providerId:p.id,expectedRevision:String(p.revision)});
  const action=(kind,request,status=200)=>api("/api/provider-source-operations",{kind,request},status);
  const custom=()=>({...provider,id:"custom-"+randomUUID(),name:"Unified source operation",revision:0,configured:false,models:["model-a"],model:"model-a",modelCatalog:null});
  const request=async(p,source,expectedSourceRevision=null,kind="save")=>{
    const scope=await protocol();return { operation:{storeId:scope.storeId,operationId:randomUUID(),expectedSequence:scope.sequence,kind,provider:p},source,expectedSourceRevision };
  };
  const ownedBindings=new Set();
  const bind=async(p)=>{
    const scope=await protocol(),target={kind:"draft",label:p.name,endpoint:p.endpoint,protocol:p.protocol,vendor:p.vendor,credentialRef:p.credentialRef};
    const previous=await api("/api/provider-catalog/status",{pluginId:plugin.manifest.id,digest:plugin.digest});
    const state=await scoped(scope.storeId,{pluginId:plugin.manifest.id,digest:plugin.digest,action:{kind:"bind",target,allowPrivateNetwork:true}});
    const binding=state.bindings.find((b)=>b.label===p.name&&b.endpoint===p.endpoint&&b.authorized&&!b.providerId);
    assert(binding);if(!previous.bindings.some((b)=>b.bindingId===binding.bindingId))ownedBindings.add(binding.bindingId);return {pluginId:plugin.manifest.id,digest:plugin.digest,bindingId:binding.bindingId,target};
  };
  const p=custom(),catalog=await bind(p), input=await request(p,{kind:"external",catalog});
  let before=posts(),readBefore=gets(),nativeBefore=nativeGets();
  const external=await action("commit",input);
  assert.equal(external.status,"committed");assert.equal(external.verification,null);
  assert.equal(posts(),before);assert.equal(gets(),readBefore);assert.equal(nativeGets(),nativeBefore);
  assert.deepEqual(await action("query",input),external);
  passed("统一入口外部手动保存保持原回执，不读目录或发送模型请求");
  const saved=external.provider, q=query(saved,input.operation.storeId);
  const source=await api("/api/provider-catalog-source",{kind:"state",query:q});assert.equal(source.kind,"external");assert.equal(source.authorized,false);
  const reset=await request(saved,{kind:"builtin"},source.sourceRevision);
  const builtin=await action("commit",reset);assert.equal(builtin.status,"committed");
  const current=await api("/api/provider-catalog-source",{kind:"state",query:query(builtin.provider,q.storeId)});
  assert.equal(current.kind,"builtin");assert.equal(current.authorized,true);assert.notEqual(current.sourceRevision,source.sourceRevision);
  assert.deepEqual(await action("commit",reset),builtin);assert.deepEqual(await api("/api/provider-operations",reset.operation),builtin);
  assert.equal(posts(),before);assert.equal(gets(),readBefore);assert.equal(nativeGets(),nativeBefore);
  const altered={...reset,expectedSourceRevision:null};assert.equal((await action("query",altered,503)).outcomeUnknown,true);
  passed("显式内置重置与资料共用原操作提交，旧入口独立读回执，错误来源令牌不能冒充原请求");
  const stale=await request(builtin.provider,{kind:"external",catalog:await bind(builtin.provider)},source.sourceRevision);
  const clock=(await protocol()).sequence;
  await action("commit",stale,400);assert.equal((await protocol()).sequence,clock);
  assert.equal((await api("/api/provider-catalog-source",{kind:"state",query:query(builtin.provider,q.storeId)})).kind,"builtin");
  assert.equal(posts(),before);assert.equal(gets(),readBefore);
  passed("过期来源令牌拒绝手动保存，不推进原 SQL 时钟或覆盖当前来源");
  const auto=custom(),autoInput=await request(auto,{kind:"external",catalog:await bind(auto)},null,"connect");
  const connected=await action("commit",autoInput);assert.equal(connected.status,"committed");assert.equal(connected.verification.state,"verified");
  assert.equal(posts(),before+1);assert.equal(nativeGets(),nativeBefore);
  assert.deepEqual(await action("commit",autoInput),connected);assert.equal(posts(),before+1);
  passed("统一外部自动连接沿用固定协议与原验证回执，重试不重复读取或发送");
  const native=custom(),nativeInput=await request(native,{kind:"builtin"},null,"connect");
  before=posts();nativeBefore=nativeGets();
  const nativeConnected=await action("commit",nativeInput);assert.equal(nativeConnected.status,"committed");
  assert.equal(posts(),before+1);const delta=nativeGets()-nativeBefore;assert(delta>=1);report.explicitNativeGets=(report.explicitNativeGets??0)+delta;
  assert.deepEqual(await action("query",nativeInput),nativeConnected);assert.equal(posts(),before+1);
  passed("统一内置自动连接保留原格式识别流程，明确选择才会读取内置目录");
  const held=custom(),holdInput=await request(held,{kind:"builtin"},null,"connect");
  control.mode="hold";const arrived=new Promise((resolve)=>control.waiting=resolve);
  before=posts();nativeBefore=nativeGets();const pending=action("commit",holdInput);await arrived;
  const cancel=await api("/api/provider-operations/cancel",holdInput.operation);assert.equal(cancel.status,"cancelled");
  const cancelled=await pending;assert.equal(cancelled.status,"cancelled");
  assert.deepEqual(await action("query",holdInput),cancelled);assert.equal(posts(),before+1);
  const deltaCancelled=nativeGets()-nativeBefore;report.explicitNativeGets+=deltaCancelled;
  for(const res of control.held)res.destroy();control.mode="ok";control.waiting=null;
  assert(!(await api("/api/snapshot")).providers.some((p)=>p.id===held.id));
  passed("统一内置验证在途使用原取消回执停止后续保存，取消不会重发远端请求");
  const scope=await protocol();
  for(const bindingId of ownedBindings) await scoped(scope.storeId,{pluginId:plugin.manifest.id,digest:plugin.digest,action:{kind:"unbind",bindingId}});
  report.unifiedOwnedDraftGrantsReleased=true;
}
